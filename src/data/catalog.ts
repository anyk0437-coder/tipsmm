export function formatPkr(amount: number): string {
  return `Rs. ${Math.round(amount).toLocaleString('en-PK')}`;
}

export function pkrToUsdt(amountPkr: number): number {
  return Number((amountPkr / USDT_RATE_PKR).toFixed(2));
}

export function formatUsdt(amountPkr: number): string {
  return `${pkrToUsdt(amountPkr).toFixed(2)} USDT`;
}
